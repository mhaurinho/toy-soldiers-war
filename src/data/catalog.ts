export type Role = 'infantry' | 'helicopter' | 'jet' | 'car' | 'tank' | 'heavy' | 'emplacement';

export interface WeaponDef {
  range: number;
  minRange: number;
  damage: number;
  period: number;
  aoe: number;
  /** 0 = hitscan. */
  speed: number;
  arc: boolean;
  indirect: boolean;
  vsGround: number;
  vsAir: number;
  accuracy: number;
  /** 0 ignores armor poorly, 1 punches through. */
  pen: number;
  homing: boolean;
  kind: 'bullet' | 'shell' | 'rocket' | 'missile' | 'bomb';
}

export interface AbilityDef {
  id: 'barrage' | 'aura' | 'mark';
  cooldown: number;
  range: number;
  radius: number;
  reduction: number;
  damage: number;
  aoe: number;
}

export interface UnitDef {
  id: string;
  name: string;
  blurb: string;
  role: Role;
  cost: number;
  hp: number;
  armor: number;
  speed: number;
  turn: number;
  vision: number;
  radius: number;
  eye: number;
  flying: boolean;
  altitude: number;
  immobile: boolean;
  weapon: WeaponDef | null;
  ability: AbilityDef | null;
  /** Cover granted to nearby friendlies. */
  cover: number;
  coverRadius: number;
  garrison: number;
  mesh: string;
  turret?: string;
  rotor?: boolean;
  scale: number;
  tags: string[];
}

