export function emptyLoadout(): Record<string, number> {
  const counts: Record<string, number> = {};
  for (const def of CATALOG) counts[def.id] = 0;
  return counts;
}

export function cloneLoadout(counts: Record<string, number>): Record<string, number> {
  return { ...emptyLoadout(), ...counts };
}

export function loadoutCost(counts: Record<string, number>): number {
  let cost = 0;
  for (const def of CATALOG) cost += (counts[def.id] ?? 0) * def.cost;
  return cost;
}

export function roleCounts(counts: Record<string, number>): Record<Role, number> {
  const roles = { infantry: 0, helicopter: 0, jet: 0, car: 0, tank: 0, heavy: 0, emplacement: 0 };
  for (const def of CATALOG) roles[def.role] += counts[def.id] ?? 0;
  return roles;
}

export function validateLoadout(counts: Record<string, number>): string[] {
  const errors: string[] = [];
  const roles = roleCounts(counts);
  const cost = loadoutCost(counts);
  for (const def of CATALOG) {
    const n = counts[def.id] ?? 0;
    if (!Number.isInteger(n) || n < 0) errors.push(`${def.name}: quantidade inválida.`);
  }
  (Object.keys(CAPS) as Role[]).forEach((role) => {
    if (roles[role] > CAPS[role]) {
      const noun = CAPS[role] === 1 ? '1' : String(CAPS[role]);
      errors.push(`${ROLE_LABEL[role]}: limite de ${noun}.`);
    }
  });
  if (roles.helicopter !== 1) errors.push('Escolha exatamente um helicóptero.');
  if (roles.jet !== 1) errors.push('Escolha exatamente um caça.');
  if (cost > BUDGET) errors.push(`Orçamento estourou em ${cost - BUDGET} fichas.`);
  return errors;
}

export function isCombatant(def: UnitDef): boolean {
  return def.weapon !== null || def.role === 'infantry' || def.flying || def.role === 'tank' || def.role === 'car' || def.role === 'heavy';
}

export function canCapture(def: UnitDef): boolean {
  return !def.flying && (def.role === 'infantry' || def.role === 'car' || def.role === 'tank');
}
